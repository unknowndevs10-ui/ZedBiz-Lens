// DEMO report layouts used only by the mock API. Dev B's real generators replace these.
import { buildSimplePdf } from './simplePdf';
import { formatDate, formatKwacha, formatPercent } from './format';

export function buildFinancialReportPdf(business, dashboard) {
  const { summary, period, expenseBreakdown } = dashboard;
  const blocks = [
    { text: 'Business Financial Report', size: 20, bold: true },
    { text: `${business.name} (${business.kind}) - synthetic demo business`, size: 11, gapBefore: 4 },
    { text: `Period: ${formatDate(period.start)} to ${formatDate(period.end)}`, size: 11 },
    { text: 'DEMO - all figures are synthetic and for demonstration only.', size: 10, bold: true, gapBefore: 6 },
    { rule: true, gapBefore: 10 },
    { text: 'Summary', size: 14, bold: true, gapBefore: 8 },
    { left: 'Total sales', right: formatKwacha(summary.sales), gapBefore: 4 },
    { left: 'Total expenses', right: formatKwacha(summary.expenses) },
    { left: 'Gross profit', right: formatKwacha(summary.grossProfit) },
    { left: 'Net profit', right: formatKwacha(summary.netProfit), bold: true },
    { left: 'Profit margin', right: formatPercent(summary.margin) },
    { rule: true, gapBefore: 10 },
    { text: 'Expenses by category', size: 14, bold: true, gapBefore: 8 },
    ...(expenseBreakdown.length
      ? expenseBreakdown.map((row, i) => ({ left: row.category, right: `${formatKwacha(row.amount)}  (${formatPercent(row.share, 0)})`, gapBefore: i === 0 ? 4 : 0 }))
      : [{ text: 'No expenses recorded in this period.', gapBefore: 4 }]),
    { text: 'Generated by the ZedBiz Lens demo. This is a placeholder layout pending Dev B\'s PDF generator.', size: 9, gapBefore: 18 },
  ];
  return buildSimplePdf({ blocks });
}

export function buildTaxReportPdf(business, tax) {
  const blocks = [
    { text: 'Tax Position Report (illustrative)', size: 20, bold: true },
    { text: `${business.name} (${business.kind}) - synthetic demo business`, size: 11, gapBefore: 4 },
    { text: `Basis: last ${tax.basis.days} days of confirmed entries (${formatDate(tax.basis.start)} to ${formatDate(tax.basis.end)})`, size: 11 },
    { text: tax.disclaimer, size: 10, bold: true, gapBefore: 6 },
    { rule: true, gapBefore: 10 },
    { text: 'Turnover and threshold', size: 14, bold: true, gapBefore: 8 },
    { left: 'Turnover in basis period', right: formatKwacha(tax.turnover.period), gapBefore: 4 },
    { left: 'Annualised turnover (projection)', right: formatKwacha(tax.turnover.annualised) },
    { left: 'Illustrative VAT threshold (placeholder)', right: formatKwacha(tax.vat.threshold) },
    { left: 'Progress to threshold', right: formatPercent(tax.vat.percent) },
    { rule: true, gapBefore: 10 },
    { text: 'Regime comparison (annual, placeholder rates)', size: 14, bold: true, gapBefore: 8 },
    ...tax.regimes.map((r, i) => ({
      left: `${r.name} - ${r.rateLabel}`,
      right: r.applicable ? (r.annualLow === r.annualHigh ? formatKwacha(r.annualLow) : `${formatKwacha(r.annualLow)} - ${formatKwacha(r.annualHigh)}`) : 'Not applicable',
      gapBefore: i === 0 ? 4 : 0,
      size: 10,
    })),
    { text: 'Generated by the ZedBiz Lens demo. No tax calculation here is official. Placeholder layout pending Dev B\'s PDF generator.', size: 9, gapBefore: 18 },
  ];
  return buildSimplePdf({ headerLabel: 'DEMO - illustrative only', blocks });
}
