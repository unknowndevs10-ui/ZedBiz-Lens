// Lightweight PDF layouts generated from records confirmed in the workspace.
import { buildSimplePdf } from './simplePdf';
import { formatDate, formatKwacha, formatPercent } from './format';

export function buildFinancialReportPdf(business, dashboard) {
  const { summary, period, expenseBreakdown } = dashboard;
  const blocks = [
    { text: 'Business Financial Report', size: 20, bold: true },
    { text: `${business.name} (${business.kind})`, size: 11, gapBefore: 4 },
    { text: `Period: ${formatDate(period.start)} to ${formatDate(period.end)}`, size: 11 },
    { text: 'Prepared from confirmed entries in this pilot workspace. Check records for completeness before relying on this report.', size: 10, bold: true, gapBefore: 6 },
    { rule: true, gapBefore: 10 },
    { text: 'Summary', size: 14, bold: true, gapBefore: 8 },
    { left: 'Total sales', right: formatKwacha(summary.sales), gapBefore: 4 },
    { left: 'Total expenses', right: formatKwacha(summary.expenses) },
    { left: 'Gross profit', right: formatKwacha(summary.grossProfit) },
    { left: 'Net profit', right: formatKwacha(summary.netProfit), bold: true },
    { left: 'Profit margin', right: formatPercent(summary.margin) },
    { rule: true, gapBefore: 10 },
    { text: 'Expenses by category', size: 14, bold: true, gapBefore: 8 },
    ...(expenseBreakdown.length
      ? expenseBreakdown.map((row, i) => ({ left: row.category, right: `${formatKwacha(row.amount)}  (${formatPercent(row.share, 0)})`, gapBefore: i === 0 ? 4 : 0 }))
      : [{ text: 'No expenses recorded in this period.', gapBefore: 4 }]),
    { text: 'Generated by ZedBiz Lens from entries confirmed in this workspace. Management view; not an audited statement.', size: 9, gapBefore: 18 },
  ];
  return buildSimplePdf({ blocks });
}

export function buildTaxReportPdf(business, tax) {
  const blocks = [
    { text: 'Tax Readiness Report (illustrative)', size: 20, bold: true },
    { text: `${business.name} (${business.kind})`, size: 11, gapBefore: 4 },
    { text: `Basis: last ${tax.basis.days} days of confirmed entries (${formatDate(tax.basis.start)} to ${formatDate(tax.basis.end)})`, size: 11 },
    { text: tax.disclaimer, size: 10, bold: true, gapBefore: 6 },
    { rule: true, gapBefore: 10 },
    { text: 'Accounting summary', size: 14, bold: true, gapBefore: 8 },
    { left: 'Total sales', right: formatKwacha(tax.accounting.totalSales), gapBefore: 4 },
    { left: 'Cost of goods sold', right: formatKwacha(tax.accounting.cogs) },
    { left: 'Allowable operating expenses (flagged)', right: formatKwacha(tax.accounting.allowableOperatingExpenses) },
    { left: 'Gross profit', right: formatKwacha(tax.accounting.grossProfit) },
    { left: 'Net profit (management view)', right: formatKwacha(tax.accounting.netProfit) },
    { left: 'Owner withdrawals excluded', right: String(tax.accounting.ownerWithdrawalsExcluded) },
    { rule: true, gapBefore: 10 },
    { text: 'Turnover tax and VAT indicators', size: 14, bold: true, gapBefore: 8 },
    { left: 'Annualised turnover', right: formatKwacha(tax.turnover.annualized), gapBefore: 4 },
    { left: 'Excess-over-floor scenario', right: formatKwacha(tax.turnover.excessOnly) },
    { left: 'Full-turnover scenario', right: formatKwacha(tax.turnover.fullTurnover) },
    { left: 'Reference VAT threshold', right: formatKwacha(tax.vat.threshold) },
    { left: 'Annualised standard-rated progress', right: formatPercent(tax.vat.actualProgressPercent) },
    { left: 'Qualified input VAT', right: `${formatKwacha(tax.vat.inputVat)} (${tax.vat.inputInvoiceCount} invoices)` },
    { left: 'Output VAT', right: formatKwacha(tax.vat.outputVat) },
    { rule: true, gapBefore: 10 },
    { text: 'Income-tax estimate', size: 14, bold: true, gapBefore: 8 },
    { left: 'Annualized taxable profit', right: formatKwacha(tax.incomeTax.annualizedTaxableProfit), gapBefore: 4 },
    { left: 'Rate schedule', right: tax.incomeTax.rateLabel },
    { left: 'Illustrative income-tax estimate', right: tax.incomeTax.estimatedTax == null ? 'Tax profile incomplete' : formatKwacha(tax.incomeTax.estimatedTax) },
    { text: 'Review eligibility, deduction treatment, VAT records and statutory application with Finance/ZRA. This report does not file a return.', size: 10, bold: true, gapBefore: 10 },
    { text: 'Generated from entries confirmed in this workspace. Not a tax assessment or official liability.', size: 9, gapBefore: 18 },
  ];
  return buildSimplePdf({ headerLabel: 'ILLUSTRATIVE ONLY', blocks });
}

